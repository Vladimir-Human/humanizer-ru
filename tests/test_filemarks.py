class TestSynthidInspectWiring(unittest.TestCase):
    """I.30: filemarks --inspect заполняет synthid честно, без checkout — unavailable."""

    def test_score_synthid_not_requested_without_upstream(self):
        res = filemarks._score_synthid(Path("x.png"), None)
        self.assertEqual(res["available"], False)
        self.assertIn("не запрошен", res["note"])

    def test_score_synthid_unavailable_with_bad_upstream(self):
        with tempfile.TemporaryDirectory() as td:
            res = filemarks._score_synthid(Path("x.png"), Path(td) / "нет_checkout")
            self.assertEqual(res["available"], False)

    def test_webp_exif_strip_roundtrip(self):
        webp = (b"RIFF" + struct.pack("<I", 4 + (8 + 8 + 8 + 8))
                + b"WEBP" + b"VP8X\x0a\x00\x00\x00" + b"\x00" * 10
                + b"EXIF" + struct.pack("<I", 4) + b"AIGC"
                + b"XMP " + struct.pack("<I", 4) + b"c2pa")
        cleaned, actions = image_meta.strip_webp(webp)
        self.assertNotIn(b"AIGC", cleaned)
        self.assertNotIn(b"c2pa", cleaned)
        has_c2pa, has_ai, findings = image_meta.inspect_webp(cleaned)
        self.assertFalse(has_c2pa)
        self.assertFalse(has_ai)


