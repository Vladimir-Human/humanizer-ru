"""Round-trip тесты файлового слоя scripts/filemarks/.

Всё собирается в памяти и во временных каталогах:
  - минимальный PNG (IHDR/caBX/tEXt/IDAT/IEND) с ручной упаковкой чанков;
  - DOCX и ODT — это zip-контейнеры, которые тест создаёт через zipfile;
  - zip-бомба — валидный DOCX, у которого в central directory и local header
    записи docProps/core.xml завышен uncompressed size.

Проверяется главный контракт filemarks: clean должен давать файл, для
которого inspect больше не находит меток. Полезная нагрузка текста (пиксельные
данные PNG / document.xml DOCX / content.xml ODT) сохраняется байт-в-байт.
Медиа-части контейнера (word/media/*, Pictures/*, data-URI, вложенные PNG в
SVG) намеренно меняются: с них снимаются C2PA/EXIF, поэтому их полезная
нагрузка (пиксели) сохраняется, а байты файла — не обязаны совпадать (I.12).
Плюс проверяется отказ при zip-бомбе.
"""

